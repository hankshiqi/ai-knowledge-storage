# ==========================================
# 1. RRF (Reciprocal Rank Fusion) 倒数排名融合参数
# ==========================================
NONE_RRF_K = 60          # RRF算法中的平滑常数 k。公式为 1/(k+rank)。k=60是业界标准默认值，用于削弱排名绝对差异带来的分数波动
NODE_RRF_LIMIT_TOP = 5   # RRF融合（多路召回合并）后，截断保留的 Top-N 文档数量，用于传给后续的 Rerank 阶段

# ==========================================
# 2. Rerank (重排) 动态截断与长度控制参数
# ==========================================
RERANK_MAX_TOPK: int = 10  # 重排后允许保留的【最大】结果数（兜底上限）
RERANK_MIN_TOPK: int = 1   # 重排后允许保留的【最小】结果数（即使分数很低/被截断，也至少保底返回1条）

# 动态截断（Dynamic Truncation）参数：用于过滤“断崖式”低分结果，避免硬塞无关内容
RERANK_GAP_RATIO: float = 0.5     # 相对分数断层比例：若上一个结果分数是当前结果的 2 倍以上（或跌落到 1/2 以下），则在此处截断丢弃后续结果
RERANK_GAP_ABS: float = 0.2     # 绝对分数断层差值：若上一个结果分数减去当前结果分数的差值 > 2，则判定为分数断层，截断后续结果

# 模型输入限制参数：控制喂给 Reranker 模型的文本长度（防止爆显存或超上下文）
RERANK_MAX_INPUT_TOKENS: int = 512  # Reranker（如 bge-reranker-large）单次接收的最大 Token 数（Query + Chunk 的总长度），超出会被截断
RERANK_SUMMARY_CHAR_RATIO: float = 1.3  # 文本摘要/截断比例。可能是为了压缩长文档：按照 1.3 的字符比例截取关键段落，防止长文本占据过多 Token
RERANK_MIN_SUMMARY_CHARS: int = 50      # 摘要/截断的最小字符数。即使按照比例算出来很短，也至少保留 50 个字符，确保有基础上下文